const assert=require("node:assert/strict"), fs=require("node:fs"), vm=require("node:vm");
const html=fs.readFileSync("bestbets_reference_frontend/index.html","utf8");
const start=html.indexOf("let hzPilotLastSample=Date.now();"), end=html.indexOf("function resize(){",start);
assert(start>=0&&end>start);
let now=100000, timer, sent=[];
const state={payload:{usage_enabled:true},page:"home",loading:false};
const document={visibilityState:"visible",addEventListener(){}};
const ctx=vm.createContext({state,document,Date:{now:()=>now},window:{parent:{postMessage:v=>sent.push(v)}},setInterval:fn=>{timer=fn}});
vm.runInContext(html.slice(start,end),ctx);
const queue=()=>vm.runInContext("hzQueuePage()",ctx);
queue();state.page="games";queue();state.page="teams";queue();
assert.equal(sent.length,0);
now+=30000;timer();
assert.equal(sent.length,1);
assert.deepEqual(Array.from(sent[0].value.usage_pages),["home","games","teams"]);
state.page="players";queue();state.payload.usage_enabled=false;queue();
state.payload.usage_enabled=true;state.page="settings";queue();
now+=30000;timer();
assert.deepEqual(Array.from(sent[1].value.usage_pages),["settings"]);
document.visibilityState="hidden";state.page="props";queue();now+=30000;timer();
assert.equal(sent.length,2);
console.log("Page batching and consent/visibility checks passed");
